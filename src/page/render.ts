import type { Cause, LookupResult, TranscriptItem } from "../contract.js";
import { escapeHtml } from "./escape.js";
import { STYLE } from "./style.js";

export interface Rendered {
  status: number;
  html: string;
}

const SITE = "Transcript";

function document_(title: string, body: string): string {
  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${escapeHtml(title)}</title>
<meta name="robots" content="noindex">
<style>${STYLE}</style>
</head>
<body>
<div class="wrap">
${body}
<footer>${SITE}. Captions only. This page reads the captions a video already carries. It does not listen to audio.</footer>
</div>
</body>
</html>`;
}

function readable(when: string): string {
  const at = new Date(when);
  if (Number.isNaN(at.getTime())) return when;
  return at.toISOString().replace("T", " ").slice(0, 16) + " UTC";
}

function whoWroteIt(kind: string): string {
  if (kind === "asr") return "generated by machine";
  if (kind === "standard") return "written by a person";
  return "unknown";
}

// Long text is hard to read as one block, so the segments are gathered into paragraphs of roughly
// this many characters. The captions carry no paragraph of their own.
const PARAGRAPH_CHARS = 700;

export function paragraphsOf(item: TranscriptItem): string[] {
  const paragraphs: string[] = [];
  let current = "";
  for (const segment of item.segments) {
    current = current ? `${current} ${segment.text}` : segment.text;
    if (current.length >= PARAGRAPH_CHARS) {
      paragraphs.push(current);
      current = "";
    }
  }
  if (current) paragraphs.push(current);
  if (paragraphs.length === 0 && item.text) paragraphs.push(item.text);
  return paragraphs;
}

function header(item: TranscriptItem): string {
  const meta = [
    `<li>Video <b>${escapeHtml(item.video_id)}</b></li>`,
    item.has_captions ? `<li>Captions <b>${escapeHtml(whoWroteIt(item.track_kind))}</b></li>` : "",
    item.has_captions && item.track_name ? `<li>Track <b>${escapeHtml(item.track_name)}</b></li>` : "",
    `<li>Read <b>${escapeHtml(readable(item.fetched_at))}</b></li>`,
  ]
    .filter(Boolean)
    .join("\n    ");
  return `<header>
  <p class="eyebrow">${SITE}</p>
  <h1>${escapeHtml(item.title)}</h1>
  <ul class="meta">
    ${meta}
  </ul>
</header>`;
}

function transcriptPage(item: TranscriptItem): Rendered {
  const body = paragraphsOf(item)
    .map((p) => `<p>${escapeHtml(p)}</p>`)
    .join("\n  ");
  return {
    status: 200,
    html: document_(item.title, `${header(item)}
<article class="transcript">
  ${body}
</article>
<p class="note"><span>Source: ${escapeHtml(item.source)}</span></p>`),
  };
}

function noCaptionsPage(item: TranscriptItem): Rendered {
  return {
    status: 200,
    html: document_(item.title, `${header(item)}
<div class="note">
  <h2>This video has no captions</h2>
  <p>There is nothing to read. The video carries no caption track, so there is no text to show.</p>
  <p>This page reads captions only. It does not listen to the audio and it does not write text from
  speech. If somebody adds captions to the video later, come back and the text will be here.</p>
</div>`),
  };
}

function problemPage(status: number, title: string, lines: string[]): Rendered {
  const body = lines.map((l) => `  <p>${l}</p>`).join("\n");
  return {
    status,
    html: document_(title, `<header>
  <p class="eyebrow">${SITE}</p>
  <h1>${escapeHtml(title)}</h1>
</header>
<div class="note">
${body}
</div>
<form action="/videos" method="get">
  <label for="id">Try another video id</label>
  <input type="text" id="id" name="id" inputmode="latin" autocomplete="off"
         placeholder="gyN9lV9QgyA" pattern="[A-Za-z0-9_-]{11}" required>
  <button type="submit">Read it</button>
</form>`),
  };
}


// One page per cause. A refusal is not a missing video, so none of these answers 404, and none of
// them tells the reader to try again when trying again cannot work.
//
// Every refusal offers the video on the platform itself, because that is the way onward that does
// work while this page cannot read it.
interface Refusal {
  status: number;
  title: string;
  lines: (videoId: string) => string[];
}

function watchLink(videoId: string): string {
  const id = escapeHtml(videoId);
  return `You can watch it on the platform:
     <a href="https://www.youtube.com/watch?v=${id}">youtube.com/watch?v=${id}</a>.`;
}

