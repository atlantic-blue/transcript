export function renderUnknownRoute(): Rendered {
  return problemPage(404, "There is nothing here", [
    `This page serves one address: <code>/videos?id=&lt;video id&gt;</code>.`,
    `Go to <a href="/">the front page</a> to start from there.`,
  ]);
}
